"""Regenerate the B5 results table (and the other report tables) from evals/results/*.json.
Writes evals/results/results_table.md and updates the block between markers in README.md.
Every number printed here is read from a results file - nothing is typed by hand."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "evals" / "results"


def load(name: str) -> dict | None:
    p = R / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def f(x, nd=3):
    return "–" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def main() -> None:
    rag, out, dec, abl, mac, tool, judge = (load(n) for n in ("rag_variants", "gigsim_outcomes", "decisions", "ablation", "multiagent_compare", "tool_design", "judge_calibration"))
    lines = ["<!-- results:start (generated by scripts/results_table.py from evals/results/*.json) -->"]
    lines += ["### B5 results table", "", "| Variant | Evidence Recall@5 | nDCG@10 | Unsupported claims / proposal (after verification) | Judge score | GigSim reply rate (mean p) | p95 latency (s) | Cost / proposal (USD) |", "|---|---|---|---|---|---|---|---|"]
    best = (out or {}).get("variants", {})
    judge_txt = f"uncalibrated (κ={judge['quadratic_weighted_kappa']})" if judge else "not calibrated yet"
    for v, label in (("v0_naive", "V0"), ("v_best", "Your best (v_best)")):
        r = (rag or {}).get("variants", {}).get(v, {}).get("breakdown", {}).get("all", {})
        o = best.get(v, {}).get("summary", {})
        lines.append(f"| {label} | {f(r.get('recall@5'))} | {f(r.get('ndcg@10'))} | {f(o.get('unsupported_claims_per_proposal_before'), 2)} → {f(o.get('unsupported_claims_per_proposal_after'), 2)} | "
                     f"{judge_txt} | {f(o.get('reply_prob_mean'))} | {f(o.get('p95_latency_s'), 2)} | {f(o.get('cost_per_proposal_usd'), 5)} |")
    if rag:
        lines += ["", f"### All retrieval variants (dev set, {rag.get('limit_per_persona')} jobs/persona, profile `{rag['env']['profile']}`, commit `{rag['env']['commit']}`)", "",
                  "| Variant | Recall@5 | MRR | nDCG@10 | Recall@5 multi-req | Recall@5 vague | p95 latency (s) |", "|---|---|---|---|---|---|---|"]
        for v, d in rag["variants"].items():
            b = d["breakdown"]
            lines.append(f"| {v} | {f(b['all']['recall@5'])} | {f(b['all']['mrr'])} | {f(b['all']['ndcg@10'])} | {f(b.get('type:multi_req', {}).get('recall@5'))} | "
                         f"{f(b.get('type:vague', {}).get('recall@5'))} | {f(d['p95_latency_s'], 2)} |")
    if abl:
        lines += ["", "### Ablation of the shipped pipeline", "", "| Configuration | Recall@5 | MRR | nDCG@10 |", "|---|---|---|---|"]
        for k, d in abl["ablations"].items():
            lines.append(f"| {k} | {f(d['all']['recall@5'])} | {f(d['all']['mrr'])} | {f(d['all']['ndcg@10'])} |")
    if dec:
        m = dec["metrics"]["all"]
        lines += ["", "### Decisions (dev set)", "", "| Bid F1 | Accuracy | Scam precision | Scam recall | Price in fair band | p95 s / job analysed |", "|---|---|---|---|---|---|",
                  f"| {f(m['bid']['f1'])} | {f(m['accuracy'])} | {f(m['scam']['precision'])} | {f(m['scam']['recall'])} | {f(m['price_in_band'])} | {f(dec['latency_per_job_s']['p95'], 2)} |"]
    if out and "x2_ab" in out:
        x = out["x2_ab"]
        lines += ["", "### X2 proposal A/B (paired)", "", "| Arm | Reply rate (mean p) | Sampled reply rate |", "|---|---|---|",
                  f"| A evidence-first | {f(x['A']['reply_prob_mean'])} | {f(x['A']['reply_rate_sampled'])} |",
                  f"| B question-first | {f(x['B']['reply_prob_mean'])} | {f(x['B']['reply_rate_sampled'])} |",
                  "", f"Paired t-test p = {f((x.get('paired_t') or {}).get('p'), 4)}, Wilcoxon p = {f(x.get('wilcoxon_p'), 4)}, McNemar p = {f(x['mcnemar_sampled_replies']['p'], 4)} (n = {x['n_pairs']} jobs)."]
    if mac:
        lines += ["", "### R&D C: single agent vs supervisor vs graph", "", "| System | Bid/skip acc. | Unsupported claims | Violations caught | Reply p | Tokens / job | p95 s |", "|---|---|---|---|---|---|---|"]
        for k, s in mac["summary"].items():
            lines.append(f"| {k} | {f(s['bid_skip_accuracy'])} | {f(s['unsupported_claims_per_proposal'], 2)} | {f(s['compliance_violations_caught_per_proposal'], 2)} | {f(s['reply_prob_mean'])} | {f(s['tokens_per_job'], 0)} | {f(s['p95_latency_s'], 1)} |")
    if tool:
        lines += ["", "### R&D A: tool granularity", "", "| Tool set | Tools | Selection acc. | Argument acc. | Tokens / task |", "|---|---|---|---|---|"]
        for k, s in tool["results"].items():
            lines.append(f"| {k} | {s['n_tools']} | {f(s['tool_selection_accuracy'])} | {f(s['argument_accuracy'])} | {f(s['tokens_per_task'], 0)} |")
    lines.append("<!-- results:end -->")
    md = "\n".join(lines) + "\n"
    (R / "results_table.md").write_text(md, encoding="utf-8")
    readme = ROOT / "README.md"
    if readme.exists():
        t = readme.read_text(encoding="utf-8")
        if "<!-- results:start" in t:
            t = re.sub(r"<!-- results:start.*?<!-- results:end -->\n?", md, t, flags=re.S)
            readme.write_text(t, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
